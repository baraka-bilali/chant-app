// Generates dist/sw.js after `expo export -p web`: a small service worker that caches the whole app
// so it opens without internet (the 854 songs are bundled in the JavaScript).
// Usage: node scripts/build-sw.js [distDir]
const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

const dist = path.resolve(process.argv[2] ?? 'dist')

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name)
    return entry.isDirectory() ? walk(full) : [full]
  })
}

const files = walk(dist)
  .map((file) => path.relative(dist, file).split(path.sep).join('/'))
  .filter((file) => file !== 'sw.js' && !file.endsWith('.map'))
  .sort()

// The cache name changes whenever any file (or this script) changes, so old caches are removed on update.
const hash = crypto.createHash('sha1').update(fs.readFileSync(__filename))
for (const file of files) hash.update(file).update(fs.readFileSync(path.join(dist, file)))
const version = hash.digest('hex').slice(0, 10)

// Keep "[" and "]" as written: the bundle requests route chunks like "[id]-hash.js" with raw brackets,
// and a cache entry with "%5B" would not match them when offline.
const toUrl = (file) => '/' + encodeURI(file).replace(/%5B/g, '[').replace(/%5D/g, ']')
const urls = ['/', ...files.map(toUrl)]

const sw = `// Generated by scripts/build-sw.js — do not edit.
const CACHE = 'recueil-${version}';
const PRECACHE = ${JSON.stringify(urls)};

// A redirected response cannot be used to answer a page navigation, so store a clean copy.
function precache() {
  return caches.open(CACHE).then((cache) =>
    Promise.all(
      PRECACHE.map((url) =>
        fetch(url, { cache: 'reload' }).then((response) => {
          if (!response.ok) throw new Error(url + ' ' + response.status);
          if (!response.redirected) return cache.put(url, response);
          return response.blob().then((body) =>
            cache.put(url, new Response(body, { status: 200, statusText: 'OK', headers: response.headers }))
          );
        })
      )
    )
  );
}

self.addEventListener('install', (event) => {
  event.waitUntil(precache().then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('recueil-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Pages: network first (fresh version when online), cached app shell when offline or slow.
function navigate(request) {
  const cached = () => caches.match('/').then((r) => r || caches.match('/index.html'));
  const timeout = new Promise((resolve) => setTimeout(() => resolve(null), 3000));
  return Promise.race([fetch(request).catch(() => null), timeout]).then((response) => response || cached());
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(navigate(request));
    return;
  }

  // Assets: cache first (files are content-hashed by the build), then network and remember.
  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
    )
  );
});
`

fs.writeFileSync(path.join(dist, 'sw.js'), sw)
console.log(`sw.js written: ${urls.length} files precached, version ${version}`)
